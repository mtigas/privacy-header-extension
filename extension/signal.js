// Runs in the page's main world at document_start, in every frame, with no
// extension APIs. It mirrors the request headers in script-visible form:
//
//   navigator.globalPrivacyControl === true   (Sec-GPC: 1)
//   navigator.doNotTrack === "1"              (DNT: 1)
//
// The accessors live on Navigator.prototype, as the native ones would, and
// are taken from an object literal so they get real accessor names rather
// than "get". A receiver check keeps them from answering for arbitrary
// objects, like a WebIDL attribute. It is safe to run more than once in the
// same global: an already-correct value is left alone.
//
// On the sites in rules/site-exceptions.json it does nothing. Like the header
// rules (excludedDomains, which WebKit checks against the top-level page), it
// decides by the top-level page rather than by its own frame, so the script
// signal and the headers always agree: a third-party frame on an excluded page
// stays silent, and an excluded site's frame embedded elsewhere is signalled.

